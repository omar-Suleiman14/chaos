/** Lesson covers are https links or one of the bundled gallery images. */
export function isCoverUrl(url: string | undefined): url is string {
  return !!url && (url.startsWith("https://") || /^\/covers\/[a-z0-9/_-]+\.(jpg|svg)$/.test(url));
}

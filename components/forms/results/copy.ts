/** "1m 05s" style durations; "—" when not recorded. */
export function formatDuration(ms: number | null | undefined, locale: "en" | "ar"): string {
  if (ms === null || ms === undefined) return "—";
  const s = Math.round(ms / 1000);
  if (locale === "ar") return s < 60 ? `${s} ث` : `${Math.floor(s / 60)} د ${s % 60} ث`;
  return s < 60 ? `${s}s` : `${Math.floor(s / 60)}m ${s % 60}s`;
}

// OAuth Provider adds tables to the standard Convex Better Auth component.
// Regenerate after updating either package: node scripts/generate-auth-schema.mjs
import { oauthProvider } from "@better-auth/oauth-provider";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
const require = createRequire(import.meta.url);
const base = readFileSync(
  join(
    dirname(require.resolve("@convex-dev/better-auth/package.json")),
    "src/component/schema.ts",
  ),
  "utf8",
);
const baseTables = base
  .slice(base.indexOf("export const tables ="), base.indexOf("const schema ="))
  .replace("export const tables =", "const baseTables =");
const schema = oauthProvider({
  loginPage: "/sign-in",
  consentPage: "/auth/consent",
}).schema;
const validators = {
  string: "v.string()",
  boolean: "v.boolean()",
  number: "v.number()",
  date: "v.number()",
  "string[]": "v.array(v.string())",
  json: "v.any()",
};
const tables = Object.entries(schema).map(([model, { fields }]) => {
  const entries = Object.entries(fields).map(([name, field]) => {
    const validator = validators[field.type];
    if (!validator) throw new Error(`Unsupported field type: ${field.type}`);
    return `    ${name}: ${field.required === false ? `v.optional(v.union(v.null(), ${validator}))` : validator},`;
  });
  const indexes = Object.keys(fields).map(
    (name) => `.index(${JSON.stringify(name)}, [${JSON.stringify(name)}])`,
  );
  if (model === "oauthConsent" || model === "oauthRefreshToken")
    indexes.push('.index("clientId_userId", ["clientId", "userId"])');
  return `  ${model}: defineTable({\n${entries.join("\n")}\n  })${indexes.join("\n    ")},`;
});
// The standard schema is maintained by the component package; extend it locally.
writeFileSync(
  "convex/betterAuth/schema.ts",
  `// Generated by scripts/generate-auth-schema.mjs.\n// Preserve upstream index names: the Better Auth adapter selects these by field.\n/* eslint-disable @convex-dev/no-duplicate-indexes */\nimport { defineSchema, defineTable } from "convex/server";\nimport { v } from "convex/values";\n${baseTables}\nexport default defineSchema({ ...baseTables,\n${tables.join("\n")}\n});\n`,
);
